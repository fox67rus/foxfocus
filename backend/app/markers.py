"""Словари признаков текста: одни и те же слова нужны и моку модели, и правилам проверки."""

ACTION_MARKERS = (
    "сделать",
    "сделай",
    "отправить",
    "отправь",
    "купить",
    "купи",
    "оплатить",
    "оплати",
    "позвонить",
    "написать",
    "напиши",
    "подготовить",
    "подготовь",
    "заказать",
    "продлить",
    "проверить",
    "созвон",
    "встреча",
    "договор",
    "счёт",
    "счет",
)

NOTE_MARKERS = ("идея", "мысль", "заметка", "наблюдение", "интересно", "почитать", "ссылка")

HIGH_PRIORITY_MARKERS = ("срочно", "срочный", "asap", "горит", "немедленно")
LOW_PRIORITY_MARKERS = ("когда-нибудь", "не срочно", "не горит")

# Вход слишком общий: конкретного действия и срока из него не вытащить.
VAGUE_MARKERS = (
    "сделай важное",
    "сделай что-нибудь",
    "разберись",
    "разберусь",
    "как-нибудь",
    "потом посмотрю",
    "что-то надо",
)

# Попытка перебить инструкции системного промпта пользовательским текстом.
INJECTION_MARKERS = (
    "игнорируй",
    "игнорируйте",
    "забудь",
    "забудьте",
    "не следуй",
    "новые инструкции",
    "system prompt",
    "ignore previous",
    "ignore all",
    "disregard",
)


def contains(text: str, markers: tuple[str, ...]) -> bool:
    lowered = text.lower()
    return any(marker in lowered for marker in markers)


def has_mixed_intents(text: str) -> bool:
    """И действие, и заметка в одном тексте: несводимые намерения, один элемент не честен."""
    return contains(text, ACTION_MARKERS) and contains(text, NOTE_MARKERS)
